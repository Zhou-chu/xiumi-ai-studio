import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'

for (const viewport of [{ name: 'desktop', width: 1440, height: 900 }, { name: 'tablet', width: 1024, height: 768 }, { name: 'mobile', width: 390, height: 844 }]) {
  test(`soft dark overlay: ${viewport.name} keeps form, focus and article stable`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.addInitScript(() => { if (window.top === window) localStorage.setItem('xiumi-color-mode', 'dark') })
    await page.goto('/')
    await expect(page.getByTestId('canvas')).toBeVisible()
    const title = page.getByLabel('文章标题', { exact: true })
    await title.fill('浮层验收：计算机系统概论')
    const article = await page.getByTestId('canvas').innerHTML()
    await page.getByTestId('toolbar-more').click()
    const trigger = page.getByTestId('open-ai-settings')
    await trigger.click()
    const dialog = page.getByRole('dialog')
    const mask = page.locator('.modal-mask')
    await expect(dialog).toHaveCSS('border-top-left-radius', '20px')
    await expect(dialog).toHaveCSS('background-color', 'rgb(27, 27, 26)')
    await expect(dialog.locator('.modal-body')).toHaveCSS('background-color', 'rgb(27, 27, 26)')
    await expect(mask).toHaveCSS('backdrop-filter', 'blur(6px)')
    expect(await dialog.evaluate(el => getComputedStyle(el).backgroundImage)).toContain('radial-gradient')
    expect(await dialog.locator('header').evaluate(el => getComputedStyle(el).backgroundImage)).toContain('radial-gradient')
    expect(await dialog.locator('.modal-body').evaluate(el => getComputedStyle(el).backgroundImage)).toContain('radial-gradient')
    await expect(page.locator('.phone')).toHaveCSS('background-image', 'none')
    await expect(page.locator('.phone')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    expect(await page.getByTestId('canvas').innerHTML()).toBe(article)
    await page.getByTestId('ai-add-preset').selectOption('custom')
    const model = page.getByTestId('ai-model')
    await model.fill('local-layout-check')
    await expect(model).toHaveValue('local-layout-check')
    await expect(dialog.locator('.ai-form')).toHaveCSS('background-color', 'rgb(27, 27, 26)')
    await expect(dialog.locator('.ai-form')).toHaveCSS('background-image', 'none')
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width)
    expect(await dialog.locator('.modal-body').evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
    const bounds = (await dialog.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(viewport.width)
    if (viewport.width === 390) {
      expect(Math.round(bounds.y + bounds.height)).toBe(viewport.height)
      await expect(dialog).toHaveCSS('border-bottom-left-radius', '0px')
    }
    await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toBeInViewport({ ratio: 1 })
    await page.evaluate(() => document.fonts.ready)
    mkdirSync('visual-evidence/diffused-picker/after', { recursive: true })
    await page.screenshot({ animations: 'disabled', path: `visual-evidence/diffused-picker/after/settings-${viewport.name}.png` })
    const cdp = await page.context().newCDPSession(page)
    await cdp.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-transparency', value: 'reduce' }] })
    await expect(mask).toHaveCSS('backdrop-filter', 'none')
    await expect(mask).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.78)')
    await expect(mask).toHaveCSS('background-image', 'none')
    await expect(dialog).toHaveCSS('background-image', 'none')
    await expect(dialog.locator('.modal-body')).toHaveCSS('background-color', 'rgb(27, 27, 26)')
    await cdp.send('Emulation.setEmulatedMedia', { features: [{ name: 'forced-colors', value: 'active' }] })
    await expect(mask).toHaveCSS('backdrop-filter', 'none')
    await expect(dialog).toHaveCSS('box-shadow', 'none')
    await cdp.send('Emulation.setEmulatedMedia', { features: [] })
    await cdp.detach()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await expect(title).toHaveValue('浮层验收：计算机系统概论')
    expect(await page.getByTestId('canvas').innerHTML()).toBe(article)
  })
}
