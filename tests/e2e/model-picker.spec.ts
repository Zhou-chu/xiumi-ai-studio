import { expect, test } from '@playwright/test'

for (const width of [1440,390]) test(`model picker folds and scrolls 40 models with keyboard at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:width===390?844:900})
  await page.addInitScript(()=>{if(window.top===window)localStorage.setItem('xiumi-color-mode','dark')})
  await page.route('**/api/settings/ai',route=>route.fulfill({json:{activeId:'picker',profiles:[{id:'picker',name:'Picker fixture',provider:'openai',baseUrl:'https://example.invalid/v1',apiKey:'',model:'manual-model',jsonMode:true}]}}))
  const models=Array.from({length:40},(_,i)=>({id:'model-'+String(i).padStart(2,'0'),contextWindow:128000+i,maxOutput:4096+i,efforts:['low','high']}))
  await page.route('**/api/settings/ai/models',route=>route.fulfill({json:models}))
  await page.goto('/')
  await page.getByTestId('toolbar-more').click()
  await page.getByTestId('open-ai-settings').click()
  await page.getByRole('button',{name:'编辑模型：Picker fixture',exact:true}).click()
  await page.getByTestId('ai-load-models').click()
  const trigger=page.getByTestId('ai-model-picker')
  await expect(trigger).toHaveAttribute('aria-expanded','false')
  const list=page.getByRole('listbox',{name:'可用模型'})
  await expect(list).toHaveCount(0)
  await trigger.focus()
  const pageScroll=await page.evaluate(()=>({x:window.scrollX,y:window.scrollY}))
  await page.keyboard.press('ArrowDown')
  await expect(list.getByRole('option')).toHaveCount(40)
  expect((await list.boundingBox())!.height).toBeLessThanOrEqual(250)
  expect(await list.evaluate(el=>el.scrollHeight>el.clientHeight)).toBe(true)
  const body=page.getByRole('dialog').locator('.modal-body')
  expect(await page.evaluate(()=>({x:window.scrollX,y:window.scrollY}))).toEqual(pageScroll)
  const bounds=await body.boundingBox()
  const listBounds=await list.boundingBox()
  expect(listBounds!.y).toBeGreaterThanOrEqual(bounds!.y)
  expect(listBounds!.y+listBounds!.height).toBeLessThanOrEqual(bounds!.y+bounds!.height)
  // Synthetic 40-model discovery fixture: scroll acceptance, not live provider evidence.
  await page.screenshot({path:`visual-evidence/diffused-picker/after/picker-${width}-open.png`})
  await list.hover()
  const scroll=await body.evaluate(el=>el.scrollTop)
  await page.mouse.wheel(0,400)
  await expect.poll(()=>list.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  expect(await body.evaluate(el=>el.scrollTop)).toBe(scroll)
  await page.keyboard.press('Home')
  await page.keyboard.press('End')
  await expect(list).toHaveAttribute('aria-activedescendant',/-option-39$/)
  expect(await list.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
  expect(await body.evaluate(el=>el.scrollTop)).toBe(scroll)
  await page.screenshot({path:`visual-evidence/diffused-picker/after/picker-${width}-scrolled.png`})
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('ai-model')).toHaveValue('model-38')
  await expect(page.getByTestId('ai-context')).toHaveValue('128038')
  await expect(page.getByTestId('ai-max-output')).toHaveValue('4134')
  await expect(trigger).toBeFocused()
  await expect(list).toHaveCount(0)
  await page.keyboard.press('ArrowDown')
  await expect(list.getByRole('option',{selected:true})).toContainText('model-38')
  await page.keyboard.press('Home')
  await page.keyboard.press('Space')
  await expect(page.getByTestId('ai-model')).toHaveValue('model-00')
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(trigger).toBeFocused()
  await expect(list).toHaveCount(0)
  await trigger.click()
  await page.keyboard.press('Tab')
  await expect(list).toHaveCount(0)
  await expect(trigger).not.toBeFocused()
  await page.getByTestId('ai-model').fill('handwritten-model')
  await expect(page.getByTestId('ai-context')).toHaveValue('')
  await expect(page.getByTestId('ai-max-output')).toHaveValue('')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
