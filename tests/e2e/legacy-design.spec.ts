import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'

const backup = fileURLToPath(new URL('../fixtures/legacy-backup/upstream-design.zip', import.meta.url))

test('restores a style-only upstream ZIP and uses the restored custom theme in an exported article', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('tab-projects').click()
  const backupButton = page.getByRole('button', { name: '项目和素材备份', exact: true })
  if (!(await backupButton.isVisible())) await page.getByTestId('toolbar-more').click()
  await backupButton.click()
  const dialog = page.getByRole('dialog', { name: '项目和素材备份', exact: true })
  const restore = dialog.getByRole('region', { name: '从整库 ZIP 恢复部分项目' })
  await restore.getByLabel('选择整库 ZIP').setInputFiles(backup)
  await restore.getByLabel('同时恢复简单模板和自定义主题').check()
  const preview = page.waitForResponse(r => new URL(r.url()).pathname === '/api/data/restore' && r.request().method() === 'POST')
  await restore.getByRole('button', { name: '预览恢复' }).click()
  expect((await preview).status()).toBe(200)
  await expect(restore.getByText('可添加的模板（1）', { exact: true })).toBeVisible()
  await expect(restore.getByText('可添加的主题（1）', { exact: true })).toBeVisible()
  const ids = async (route: string) => ((await (await page.request.get(route)).json()) as Array<{ id: string }>).map(x => x.id)
  expect(await ids('/api/templates')).not.toContain('fixture-template')
  expect(await ids('/api/themes')).not.toContain('custom-fixture')

  await restore.getByRole('button', { name: '确认添加所选数据', exact: true }).click()
  await expect(restore.getByText('新增模板（1）', { exact: true })).toBeVisible()
  await expect(restore.getByText('新增主题（1）', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.getByTestId('tab-templates').click()
  const template = page.locator('.tpl-item').filter({ hasText: 'Backup template' })
  await template.getByRole('button', { name: '新建', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '文章标题' })).toHaveValue('Backup template')
  await expect(page.getByTestId('canvas')).toContainText('Archived template heading')
  await expect(page.getByTestId('canvas')).toContainText('Archived quote')
  await page.getByTestId('open-export').click()
  const exported = page.getByRole('dialog', { name: '导出与发布', exact: true })
  await exported.getByTestId('copy-wechat').click()
  await expect(exported.getByText(/^HTML 长度 [\d,]+ 字符$/)).toBeVisible()
  const html = await page.evaluate(async () => {
    const items = await navigator.clipboard.read()
    return (await items[0].getType('text/html')).text()
  })
  expect(html).toContain('Archived template heading')
  expect(html).toContain('#112233')
})
