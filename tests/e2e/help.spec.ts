import { test, expect } from '@playwright/test'

test('annotations require sustained hover and support focus, Escape and repeat entry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '参考风格', exact: true }).click()
  const trigger = page.getByRole('button', { name: '参考风格学习说明', exact: true })
  const annotation = page.getByRole('tooltip')
  await expect(annotation).toHaveCount(0)
  await trigger.hover()
  await page.waitForTimeout(250)
  await expect(annotation).toHaveCount(0)
  await page.mouse.move(1, 1)
  await page.waitForTimeout(700)
  await expect(annotation).toHaveCount(0)
  await trigger.hover()
  await expect(annotation).toBeVisible()
  await annotation.hover()
  await expect(annotation).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(annotation).toHaveCount(0)
  await page.mouse.move(1, 1)
  // Keyboard focus exposes the explanation without waiting for a mouse.
  await page.keyboard.press('Tab')
  await trigger.focus()
  await expect(annotation).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(annotation).toHaveCount(0)
  await expect(page.getByText('我确认对参考文章拥有使用权或已获授权', { exact: true })).toBeVisible()
})

test('Escape dismisses a modal annotation before closing its dialog', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('open-preview').click()
  const dialog = page.getByRole('dialog')
  const help = dialog.getByRole('button', { name: '文章预览说明' })
  await help.hover()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})

for (const mode of ['light','dark'] as const) test(`touch can explicitly open and dismiss annotation on phone (${mode})`, async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  await context.addInitScript(mode=>{if(window.top===window)localStorage.setItem('xiumi-color-mode',mode)},mode)
  const page = await context.newPage()
  await page.goto('/')
  // Startup intentionally exposes no editing controls until its document is loaded.
  await expect(page.locator('.workspace')).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-color-mode',mode)
  if (await page.getByTestId('workspace-right').isVisible()) await page.getByTestId('workspace-right').tap()
  await page.getByRole('button', { name: '参考风格', exact: true }).tap()
  const help = page.getByRole('button', { name: '参考风格学习说明' })
  await help.tap()
  await expect(page.getByRole('tooltip')).toBeVisible()
  const box = await page.getByRole('tooltip').boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await help.tap()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await context.close()
})
