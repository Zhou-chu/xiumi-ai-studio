import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'

const backup = fileURLToPath(new URL('../fixtures/legacy-backup/upstream-library.zip', import.meta.url))

test('previews an upstream ZIP before adding its supported projects and reports what it leaves behind', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('tab-projects').click()
  const menu = page.getByTestId('toolbar-more')
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('button', { name: '项目和素材备份' }).click()
  const dialog = page.getByRole('dialog', { name: '项目和素材备份' })
  const restore = dialog.getByRole('region', { name: '从整库 ZIP 恢复部分项目' })
  await restore.getByLabel('选择整库 ZIP').setInputFiles(backup)
  const confirm = restore.getByRole('button', { name: '确认添加项目' })
  await expect(confirm).toHaveCount(0)
  await restore.getByRole('button', { name: '预览恢复' }).click()
  await expect(restore.getByRole('status')).toContainText('预计新增 2 个项目')
  expect((await page.request.get('/api/projects/corrupt')).status()).toBe(404)
  await restore.getByText('不支持的项目（1）', { exact: true }).click()
  await expect(restore.getByText('archived', { exact: true })).toBeVisible()
  await confirm.click()
  await expect(restore.getByRole('status')).toHaveText('新增 2 个项目。')
  await expect(restore.getByText('未恢复的其他档案（4）', { exact: true })).toBeVisible()
  expect((await page.request.get('/api/projects/archived')).status()).toBe(404)
  await dialog.getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.getByRole('button', { name: /Backup corrupt/ }).click()
  await expect(page.getByRole('textbox', { name: '文章标题' })).toHaveValue('Backup corrupt')
  await expect(page.getByTestId('canvas').getByText('Restored legacy heading')).toBeVisible()
  await expect(page.getByTestId('canvas').getByText('Restored card')).toBeVisible()
  await page.locator('[data-block-id="legacy-paragraph"]').dblclick()
  const editor = page.locator('.tiptap')
  await expect(editor).toBeVisible()
  await editor.press('Control+End')
  await page.keyboard.insertText(' / roundtrip edit')
  await editor.press('Escape')
  await expect(page.getByTestId('save-status')).toHaveText('已保存')
  await page.getByTestId('open-export').click()
  const exporter = page.getByRole('dialog', { name: '导出与发布' })
  await exporter.getByTestId('copy-wechat').click()
  await expect(exporter.getByText(/HTML 长度/)).toBeVisible()
  const exported = await page.evaluate(async () => {
    const items = await navigator.clipboard.read()
    return (await items[0].getType('text/html')).text()
  })
  expect(exported).toContain('Restored legacy heading')
  expect(exported).toContain('roundtrip edit')
  expect(exported).toContain('marked words')
  expect(exported).toContain('Restored card')
})
