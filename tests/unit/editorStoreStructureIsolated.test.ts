// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { createBlock } from '../../src/core/blocks'
import { allThemes } from '../../src/core/themes'
import { findBlock } from '../../src/core/tree'
import type { Block, Doc } from '../../src/core/types'
import { selectedBlock, useStore } from '../../src/editor/store'

const h=vi.hoisted(()=>({ save:vi.fn(), themes:vi.fn(), fetch:vi.fn() }))
vi.mock('../../src/editor/api',()=>({api:{saveProject:h.save,themes:h.themes}}))
const state=useStore.getState
const named=<T extends Block['type']>(type:T,id:string)=>({...createBlock(type),id})
const a=named('heading','a'), b=named('paragraph','b'), c=named('image','c')
const box={...createBlock('box',{children:[b,c]}),id:'container'}
const d=named('ending','d')
const doc:Doc={id:'fixture',title:'初稿',author:'',digest:'',themeId:'minimal-magazine',blocks:[a,box,d],createdAt:1,updatedAt:1,revision:'r1'}
const rootOrder=()=>state().doc.blocks.map(block=>block.id)
const children=()=>(findBlock(state().doc.blocks,'container')?.block as Block<'box'>).props.children.map(block=>block.id)
const noBoundary=()=>{throw Error('Unexpected isolated editor store IO')}
beforeEach(()=>{
  vi.useFakeTimers();vi.setSystemTime(10_000)
  for (const mock of Object.values(h)) mock.mockReset().mockImplementation(noBoundary)
  vi.stubGlobal('fetch',h.fetch)
  state().load(doc)
  useStore.setState({toast:null,matchColors:false})
})
afterEach(()=>{
  vi.clearAllTimers();vi.useRealTimers();vi.unstubAllGlobals()
  for (const mock of Object.values(h)) expect(mock).not.toHaveBeenCalled()
})
it('toggles selected membership, promotes the remaining active member and rejects missing IDs',()=>{
  state().select('b')
  expect(selectedBlock(state())?.id).toBe('b')
  state().select('c',{toggle:true})
  expect(state().selectedIds).toEqual(['b','c'])
  expect(state().selectedId).toBe('c')
  state().select('c',{toggle:true})
  expect(state().selectedIds).toEqual(['b'])
  expect(state().selectedId).toBe('b')
  state().select('not-there')
  expect(state().selectedIds).toEqual([])
  expect(selectedBlock(state())).toBeNull()
})
it('treats editing and photo picking as mutually exclusive and prunes them when selecting more than one',()=>{
  state().setEditing('b')
  expect(state().editingId).toBe('b')
  state().setPicking('c')
  expect(state().editingId).toBeNull()
  expect(state().pickingId).toBe('c')
  state().select('a',{toggle:true})
  expect(state().selectedIds).toEqual(['c','a'])
  expect(state().pickingId).toBeNull()
  state().setPicking('missing')
  expect(state().pickingId).toBeNull()
  state().setEditing('missing')
  expect(state().editingId).toBeNull()
  state().setMatchColors(true)
  expect(state().matchColors).toBe(true)
  expect(state().past).toHaveLength(0)
})
it('inserts inside a selected container but keeps top-level blocks outside',()=>{
  state().select('container')
  const ordinary=state().insertBlock('quote')
  expect(children()).toEqual(['b','c',ordinary])
  expect(state().selectedId).toBe(ordinary)
  const top=named('box','top-fixture')
  expect(state().insertBlock(top,1,'container')).toBe(top.id)
  expect(rootOrder()).toEqual(['a','top-fixture','container','d'])
  expect(children()).toContain(ordinary)
})
it('normalizes and clones batch insert entries rather than reusing their original identity',()=>{
  state().select('b')
  const external=named('image','c')
  state().insertBlocks([external])
  const order=children()
  expect(order[0]).toBe('b')
  expect(order[2]).toBe('c')
  expect(order[1]).not.toBe(external.id)
  expect(findBlock(state().doc.blocks,order[1])?.block.type).toBe('image')
  expect(state().selectedId).toBe('b')
  expect(external.id).toBe('c')
})
it('selects the next neighbor on single removal, and drops a selected ancestor and descendants in one commit',()=>{
  state().setEditing('b')
  state().removeBlock('b')
  expect(children()).toEqual(['c'])
  expect(state().selectedId).toBe('c')
  expect(state().editingId).toBeNull()
  state().select('container',{toggle:true})
  const past=state().past.length
  state().removeSelected()
  expect(rootOrder()).toEqual(['a','d'])
  expect(state().selectedIds).toEqual([])
  expect(state().past).toHaveLength(past+1)
  state().undo()
  expect(children()).toEqual(['c'])
  expect(state().selectedIds).toEqual([])
})
it('duplicates nested blocks, preserves original during replacement and leaves unknown operations inert',()=>{
  state().duplicateBlock('b')
  const duplicate=state().selectedId!
  expect(duplicate).not.toBe('b')
  expect(children()).toEqual(['b',duplicate,'c'])
  const substitute=named('quote','replacement')
  state().replaceBlock(duplicate,[substitute])
  expect(children()).toEqual(['b','replacement','c'])
  expect(state().selectedId).toBe('replacement')
  expect(findBlock(state().doc.blocks,'b')?.block.type).toBe('paragraph')
  const before=state().doc
  state().replaceBlock('b',[])
  state().removeBlock('unknown')
  state().duplicateBlock('unknown')
  state().moveBlock('unknown',0)
  expect(state().doc).toBe(before)
})
it('moves top-level, nested and cross-container blocks while keeping invalid moves inert',()=>{
  state().moveBlock('b',1)
  expect(children()).toEqual(['c','b'])
  state().moveBlock('a',2)
  expect(rootOrder()).toEqual(['container','d','a'])
  state().moveBlockTo('c',null,1)
  expect(rootOrder()).toEqual(['container','c','d','a'])
  expect(children()).toEqual(['b'])
  const before=state().doc
  state().moveBlockTo('container','container',0)
  expect(state().doc).toBe(before)
})
it('coalesces typed field edits for one undo, then keeps a later edit separate and clears redo after divergence',()=>{
  state().setDocFields({title:'一'},'title')
  vi.setSystemTime(10_500)
  state().setDocFields({title:'二'},'title')
  expect(state().past).toHaveLength(1)
  vi.setSystemTime(12_100)
  state().setDocFields({title:'三'},'title')
  expect(state().past).toHaveLength(2)
  state().undo();expect(state().doc.title).toBe('二')
  state().undo();expect(state().doc.title).toBe('初稿')
  state().redo();expect(state().doc.title).toBe('二')
  state().setDocFields({title:'分歧'})
  expect(state().future).toEqual([])
  state().redo();expect(state().doc.title).toBe('分歧')
  expect(state().saveStatus).toBe('dirty')
})
it('caps history and never re-exposes a stale proposal after undo or redo',()=>{
  for(let i=0;i<110;i++)state().setDocFields({title:'标题'+i})
  expect(state().past).toHaveLength(100)
  state().propose('新建议',[{op:'setMeta',title:'AI'}])
  expect(state().proposal?.items).toHaveLength(1)
  const generation=state().proposalVersion
  state().undo()
  expect(state().proposal).toBeNull()
  expect(state().proposalVersion).toBeGreaterThan(generation)
  state().redo()
  expect(state().proposal).toBeNull()
})
it('refreshes theme inventory and avoids replacing a different newer toast when the older timer fires',()=>{
  useStore.setState({themes:[]})
  state().refreshThemes()
  expect(state().themes.map(t=>t.id)).toEqual(allThemes().map(t=>t.id))
  state().notify('旧通知')
  vi.advanceTimersByTime(1000)
  state().notify('新错误','error')
  vi.advanceTimersByTime(2200)
  expect(state().toast).toEqual({text:'新错误',kind:'error'})
  vi.advanceTimersByTime(1000)
  expect(state().toast).toBeNull()
})
