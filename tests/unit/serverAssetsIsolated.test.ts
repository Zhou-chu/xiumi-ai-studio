import { join } from 'node:path'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { bestFrame, cleanCache, cropAsset, deleteAsset, listAssets, saveAsset, saveGlyph, variantPath, wechatReady, type Asset } from '../../server/assets'

const h = vi.hoisted(() => ({
  sharp: vi.fn(), budget: vi.fn(), nanoid: vi.fn(), exists: vi.fn(), read: vi.fn(), dir: vi.fn(),
  rename: vi.fn(), rm: vi.fn(), stat: vi.fn(), write: vi.fn(), readJson: vi.fn(), mutateJson: vi.fn(), safeId: vi.fn(),
}))
vi.mock('sharp', () => ({ default: Object.assign(h.sharp, { strategy: { attention: 'attention-fixture' } }) }))
vi.mock('nanoid', () => ({ nanoid: h.nanoid }))
vi.mock('node:fs', () => ({ existsSync: h.exists }))
vi.mock('node:fs/promises', () => ({ readFile: h.read, readdir: h.dir, rename: h.rename, rm: h.rm, stat: h.stat, writeFile: h.write }))
vi.mock('../../server/store', () => ({ DIRS: { assets: '/virtual/assets', cache: '/virtual/cache' }, readJson: h.readJson, mutateJson: h.mutateJson, safeId: h.safeId }))
vi.mock('../../server/imageBudget', () => ({ MAX_INPUT_PIXELS: 64_000_000, withImageBudget: h.budget }))
const assetsPath = (file: string) => join('/virtual/assets', file)
const cachePath = (file: string) => join('/virtual/cache', file)
const original: Asset = { id: 'raw', file: 'raw.png', name: '原图.png', width: 12, height: 10, size: 10, createdAt: 1 }
const bytes = Buffer.from('virtual source')
const outputs = new Set<string>()
let index: Record<string, Asset>
const unexpected = () => { throw Error('Unexpected virtual asset adapter') }
const codec = () => ({
  rotate: vi.fn<() => unknown>(), resize: vi.fn<(..._args: unknown[]) => unknown>(), jpeg: vi.fn<(..._args: unknown[]) => unknown>(),
  png: vi.fn<(..._args: unknown[]) => unknown>(), extract: vi.fn<(..._args: unknown[]) => unknown>(), flatten: vi.fn<(..._args: unknown[]) => unknown>(),
  ensureAlpha: vi.fn<() => unknown>(), metadata: vi.fn(), stats: vi.fn(),
  toBuffer: vi.fn(), toFile: vi.fn(),
})
function pipeline() {
  const p = codec()
  for (const f of [p.rotate, p.resize, p.jpeg, p.png, p.extract, p.flatten, p.ensureAlpha]) f.mockReturnValue(p)
  p.metadata.mockResolvedValue({ format: 'png', hasAlpha: true, pages: 1 })
  p.stats.mockResolvedValue({ channels: [{}, {}, {}, { mean: 9 }] })
  p.toBuffer.mockResolvedValue(bytes)
  p.toFile.mockImplementation(async (path: string) => { outputs.add(path); return { width: 8, height: 6, size: 42 } })
  return p
}
beforeEach(() => {
  for (const f of Object.values(h)) f.mockReset().mockImplementation(unexpected)
  h.nanoid.mockReturnValue('generated-id')
  h.budget.mockImplementation(async (work: () => unknown) => work())
  outputs.clear()
  index = { raw: { ...original } }
  h.readJson.mockImplementation(async () => index)
  h.mutateJson.mockImplementation(async (_path: string, _fallback: unknown, update: (i: Record<string,Asset>) => unknown) => update(index))
  h.safeId.mockImplementation((id: string) => id)
  h.exists.mockImplementation((path: string) => outputs.has(path))
  h.rename.mockImplementation(async (from: string, to: string) => {
    if (!outputs.delete(from)) throw Error('Unknown virtual temporary output')
    outputs.add(to)
  })
  h.rm.mockImplementation(async (path: string) => { outputs.delete(path) })
})
afterEach(() => vi.restoreAllMocks())
it('sorts existing catalog entries and removes only the indexed file with the given ID', async () => {
  outputs.add(assetsPath('raw.png'))
  index.newer = { ...original, id: 'newer', file: 'newer.png', createdAt: 3 }
  expect((await listAssets()).map(a => a.id)).toEqual(['newer','raw'])
  await deleteAsset('missing')
  expect(h.rm).not.toHaveBeenCalled()
  await deleteAsset('raw')
  expect(h.safeId.mock.calls).toEqual([['missing'],['raw']])
  expect(h.rm).toHaveBeenCalledExactlyOnceWith(assetsPath('raw.png'),{force:true})
  expect(await listAssets()).toEqual([index.newer])
})
it('selects the strongest meaningful frame after a nearly blank first frame', async () => {
  const p = pipeline()
  p.metadata.mockResolvedValue({ pages: 4 })
  for (const mean of [1,7,7.8,12]) p.stats.mockResolvedValueOnce({ channels: [{}, {}, {}, { mean }] })
  h.sharp.mockReturnValue(p)
  expect(await bestFrame(bytes)).toBe(3)
  expect(h.sharp.mock.calls.map(([,opts])=>opts.limitInputPixels)).toEqual([64_000_000,64_000_000,64_000_000,64_000_000,64_000_000])
  expect(h.sharp.mock.calls.slice(1).map(([,opts])=>opts.page)).toEqual([0,1,2,3])
})
it('stays on page zero when first frame is usable and only propagates the pixel-budget metadata failure', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  p.metadata.mockResolvedValueOnce({ pages: 40 })
  expect(await bestFrame(bytes)).toBe(0)
  expect(p.stats).toHaveBeenCalledTimes(1)
  p.metadata.mockRejectedValueOnce(Error('unsupported synthetic header'))
  expect(await bestFrame(bytes)).toBe(0)
  p.metadata.mockRejectedValueOnce(Error('Input image exceeds pixel limit'))
  await expect(bestFrame(bytes)).rejects.toThrow('Input image exceeds pixel limit')
  expect(p.stats).toHaveBeenCalledTimes(1)
})
it.each([['png', true, '.png'], ['gif', true, '.png'], ['jpeg', false, '.jpg']] as const)('stores %s using the recorded produced size and optional source digest', async (format, hasAlpha, ext) => {
  const p = pipeline()
  p.metadata.mockResolvedValue({ pages:1, format, hasAlpha })
  h.sharp.mockReturnValue(p)
  vi.spyOn(Date,'now').mockReturnValue(123)
  const created = await saveAsset(bytes,'选择图片', 'synthetic-digest')
  expect(created).toEqual({ id:'generated-id', file:'generated-id'+ext, width:8, height:6, size:42, name:'选择图片', createdAt:123, sourceKey:'synthetic-digest' })
  expect(index[created.id]).toBe(created)
  expect(p.rotate).toHaveBeenCalledTimes(1)
  expect(p.resize).toHaveBeenCalledExactlyOnceWith({ width:2400,height:2400,fit:'inside',withoutEnlargement:true })
  expect(ext==='.png'?p.png:p.jpeg).toHaveBeenCalledTimes(1)
  expect(ext==='.png'?p.jpeg:p.png).not.toHaveBeenCalled()
})
it('cleans only the new file if index publication fails and keeps the exact original error', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  outputs.add(assetsPath('raw.png'))
  const failure = Error('Virtual index update failed')
  h.mutateJson.mockRejectedValueOnce(failure)
  await expect(saveAsset(bytes,'bad')).rejects.toBe(failure)
  expect(h.rm).toHaveBeenCalledExactlyOnceWith(assetsPath('generated-id.png'),{force:true})
  expect([...outputs]).toEqual([assetsPath('raw.png')])
  expect(Object.keys(index)).toEqual(['raw'])
})
it('crops with bounded rounded coordinates into a new asset without modifying the source record', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  await expect(cropAsset('missing',{x:0,y:0,width:1,height:1})).rejects.toMatchObject({status:404})
  expect(h.sharp).not.toHaveBeenCalled()
  const out = await cropAsset('raw',{x:2.4,y:1.8,width:50,height:80})
  expect(p.extract).toHaveBeenCalledExactlyOnceWith({left:2,top:2,width:10,height:8})
  expect(out.name).toBe('原图-crop.png')
  expect(index.raw).toEqual(original)
  expect(h.rm).not.toHaveBeenCalled()
})
it('validates derivative source and dimensions before creating, then reuses the bounded cache record', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  await expect(variantPath('bad file.png')).rejects.toMatchObject({status:400})
  await expect(variantPath('raw.png')).rejects.toMatchObject({status:404})
  outputs.add(assetsPath('raw.png'))
  await expect(variantPath('raw.png','0:1',120)).rejects.toMatchObject({status:400})
  await expect(variantPath('raw.png','1:999',2400)).rejects.toMatchObject({status:413})
  expect(await variantPath('raw.png',undefined,4000)).toBe(assetsPath('raw.png'))
  expect(h.sharp).not.toHaveBeenCalled()
  expect(await variantPath('raw.png','3:2',120.1)).toBe(cachePath('raw_3x2_120.png'))
  expect(p.resize).toHaveBeenCalledExactlyOnceWith({width:120,height:80,fit:'cover',position:'attention-fixture'})
  expect(h.rename).toHaveBeenCalledExactlyOnceWith(cachePath('.raw_3x2_120.png.generated-id.tmp'),cachePath('raw_3x2_120.png'))
  expect(await variantPath('raw.png','3:2',120)).toBe(cachePath('raw_3x2_120.png'))
  expect(p.toFile).toHaveBeenCalledTimes(1)
})
it('rechecks inside the processing slot and never overwrites a cached result produced by an earlier task', async () => {
  outputs.add(assetsPath('raw.png'))
  h.budget.mockImplementationOnce(async (work: () => unknown) => {
    outputs.add(cachePath('raw_o_1080.png'))
    return work()
  })
  expect(await variantPath('raw.png')).toBe(cachePath('raw_o_1080.png'))
  expect(h.sharp).not.toHaveBeenCalled()
  expect(h.rename).not.toHaveBeenCalled()
})
it('checks target JPEG transport size without sending the buffer anywhere', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  h.stat.mockResolvedValueOnce({size:8}).mockResolvedValue({size:1_000_001})
  h.read.mockResolvedValueOnce(bytes)
  expect(await wechatReady('virtual/photo.png')).toEqual({buf:bytes,mime:'image/png',name:'photo.png'})
  expect(h.sharp).not.toHaveBeenCalled()
  p.toBuffer.mockResolvedValueOnce(Buffer.alloc(1_000_001)).mockResolvedValueOnce(bytes)
  expect(await wechatReady('virtual/photo.png')).toEqual({buf:bytes,mime:'image/jpeg',name:'image.jpg'})
  expect(p.jpeg.mock.calls).toEqual([[{quality:80,mozjpeg:true}],[{quality:72,mozjpeg:true}]])
  p.toBuffer.mockResolvedValue(Buffer.alloc(1_000_001))
  await expect(wechatReady('virtual/photo.png')).rejects.toThrow('图片压缩后仍超过 1MB')
})
it('never registers managed glyphs as ordinary indexed assets and only writes new verified PNGs', async () => {
  const p = pipeline()
  h.sharp.mockReturnValue(p)
  h.write.mockImplementation(async (file: string) => { outputs.add(file) })
  expect(await saveGlyph('data:image/jpg;base64,AA==')).toBeNull()
  expect(h.sharp).not.toHaveBeenCalled()
  p.metadata.mockResolvedValueOnce({format:'jpg'})
  expect(await saveGlyph('data:image/png;base64,AA==')).toBeNull()
  const glyph = await saveGlyph('data:image/png;base64,AA==')
  expect(glyph).toMatch(/^rp-[a-f0-9]{24}\.png$/)
  expect(await saveGlyph('data:image/png;base64,AA==')).toBe(glyph)
  expect(h.write).toHaveBeenCalledExactlyOnceWith(assetsPath(`.${glyph}.generated-id.tmp`),Buffer.from([0]),{flag:'wx'})
  expect(h.mutateJson).not.toHaveBeenCalled()
  expect(outputs.has(assetsPath(glyph!))).toBe(true)
})
it('clears only enumerated virtual variant cache paths', async () => {
  h.dir.mockResolvedValue(['first.png','second.jpg'])
  await cleanCache()
  expect(h.rm.mock.calls).toEqual([[cachePath('first.png'),{force:true}],[cachePath('second.jpg'),{force:true}]])
})
