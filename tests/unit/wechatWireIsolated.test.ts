import { join } from 'node:path'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const h = vi.hoisted(() => ({ read: vi.fn(), write: vi.fn(), ready: vi.fn(), fetch: vi.fn() }))
vi.mock('../../server/store', () => ({ DATA: '/synthetic-wechat', readJson: h.read, writeJson: h.write }))
vi.mock('../../server/assets', () => ({ wechatReady: h.ready }))
let api: typeof import('../../server/wechat')
const base = 'https://api.weixin.qq.com/cgi-bin'
const response = (value: unknown) => new Response(JSON.stringify(value), { headers: { 'content-type': 'application/json' } })
const draft = { title: '合成标题', content: '<p>测试</p>', thumb_media_id: 'synthetic-cover' }
beforeEach(async () => {
  vi.resetModules()
  for (const mock of Object.values(h)) mock.mockReset().mockImplementation(() => { throw Error('Unexpected synthetic WeChat boundary') })
  h.read.mockResolvedValue({ images: {}, covers: {} })
  h.write.mockResolvedValue(undefined)
  h.ready.mockResolvedValue({ buf: Buffer.from([1, 2, 3]), mime: 'image/png', name: 'synthetic.png' })
  vi.stubGlobal('fetch', h.fetch)
  vi.stubEnv('WECHAT_APPID', 'synthetic-appid'); vi.stubEnv('WECHAT_APPSECRET', 'synthetic-secret')
  vi.spyOn(Date, 'now').mockReturnValue(1000)
  api = await import('../../server/wechat')
})
afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs(); vi.restoreAllMocks() })
it('reveals only a masked configured ID and refuses missing credentials before a request', async () => {
  expect(api.wechatStatus()).toEqual({ configured: true, appid: 'synthe…' })
  vi.stubEnv('WECHAT_APPSECRET', '')
  expect(api.wechatStatus().configured).toBe(false)
  await expect(api.addDraft(draft)).rejects.toMatchObject({ status: 503 })
  expect(h.fetch).not.toHaveBeenCalled()
  vi.stubEnv('WECHAT_APPID', '')
  expect(api.wechatStatus()).toEqual({ configured: false, appid: '' })
})
it('reuses content and cover caches without encoding, fetching or rewriting them', async () => {
  const cover = { media_id: 'existing-cover', url: 'http://fixture.invalid/cover' }
  h.read.mockResolvedValue({ images: { old: 'http://mmbiz.qpic.cn/old' }, covers: { old: cover } })
  expect(await api.uploadContentImage('old', '/virtual/old')).toBe('https://mmbiz.qpic.cn/old')
  expect(await api.uploadCover('old', '/virtual/old')).toBe(cover)
  expect(h.ready).not.toHaveBeenCalled(); expect(h.fetch).not.toHaveBeenCalled(); expect(h.write).not.toHaveBeenCalled()
})
it('builds one real multipart body and persists an HTTPS content URL after token acquisition', async () => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'synthetic-token', expires_in: 7200 })).mockResolvedValueOnce(response({ url: 'http://mmbiz.qpic.cn/new' }))
  expect(await api.uploadContentImage('key', '/virtual/content.png')).toBe('https://mmbiz.qpic.cn/new')
  expect(h.ready).toHaveBeenCalledExactlyOnceWith('/virtual/content.png')
  expect(h.fetch.mock.calls[0][0]).toBe(base + '/stable_token')
  expect(JSON.parse(h.fetch.mock.calls[0][1].body)).toEqual({ grant_type: 'client_credential', appid: 'synthetic-appid', secret: 'synthetic-secret', force_refresh: false })
  const [url, init] = h.fetch.mock.calls[1]
  expect(url).toBe(base + '/media/uploadimg?access_token=synthetic-token')
  expect(init.method).toBe('POST')
  const file = (init.body as FormData).get('media') as File
  expect(file.name).toBe('synthetic.png'); expect(file.type).toBe('image/png')
  expect([...new Uint8Array(await file.arrayBuffer())]).toEqual([1, 2, 3])
  expect(h.write).toHaveBeenCalledExactlyOnceWith(join('/synthetic-wechat', 'wechat-cache.json'), { images: { key: 'https://mmbiz.qpic.cn/new' }, covers: {} })
})
it('shares a still-valid token across cover and draft requests and retains exact draft fields', async () => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'synthetic-token', expires_in: 7200 })).mockResolvedValueOnce(response({ media_id: 'new-cover', url: 'http://fixture.invalid/cover' })).mockResolvedValueOnce(response({ media_id: 'new-draft' }))
  expect(await api.uploadCover('key', '/virtual/cover')).toEqual({ media_id: 'new-cover', url: 'http://fixture.invalid/cover' })
  expect(h.fetch.mock.calls[1][0]).toBe(base + '/material/add_material?access_token=synthetic-token&type=image')
  expect(await api.addDraft({ ...draft, content_source_url: 'https://example.invalid/source' })).toEqual({ media_id: 'new-draft' })
  expect(h.fetch).toHaveBeenCalledTimes(3)
  expect(JSON.parse(h.fetch.mock.calls[2][1].body)).toEqual({ articles: [{ ...draft, content_source_url: 'https://example.invalid/source', author: '', digest: '', need_open_comment: 0, only_fans_can_comment: 0 }] })
})
it.each([40001, 42001])('refreshes an expired token once for upstream code %i', async errcode => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'old', expires_in: 7200 })).mockResolvedValueOnce(response({ errcode })).mockResolvedValueOnce(response({ access_token: 'fresh', expires_in: 7200 })).mockResolvedValueOnce(response({ media_id: 'done' }))
  expect(await api.addDraft(draft)).toEqual({ media_id: 'done' })
  expect(JSON.parse(h.fetch.mock.calls[2][1].body).force_refresh).toBe(true)
  expect(h.fetch.mock.calls[3][0]).toBe(base + '/draft/add?access_token=fresh')
  expect(h.fetch).toHaveBeenCalledTimes(4)
})
it('does not endlessly retry a refreshed but still rejected token', async () => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'old', expires_in: 7200 })).mockResolvedValueOnce(response({ errcode: 40001 })).mockResolvedValueOnce(response({ access_token: 'fresh', expires_in: 7200 })).mockResolvedValueOnce(response({ errcode: 40001 }))
  await expect(api.addDraft(draft)).rejects.toMatchObject({ status: 502, message: expect.stringContaining('access_token 无效或已过期') })
  expect(h.fetch).toHaveBeenCalledTimes(4)
})
it('requests a new token when its remaining lifetime is exactly the safety margin', async () => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'short', expires_in: 60 })).mockResolvedValueOnce(response({ media_id: 'first' })).mockResolvedValueOnce(response({ access_token: 'new', expires_in: 7200 })).mockResolvedValueOnce(response({ media_id: 'second' }))
  await api.addDraft(draft); await api.addDraft(draft)
  expect(h.fetch.mock.calls[2][0]).toBe(base + '/stable_token')
  expect(JSON.parse(h.fetch.mock.calls[2][1].body).force_refresh).toBe(false)
})
it.each([{ errcode: 48001, message: '公众号没有该接口权限' }, { errcode: 12345, errmsg: 'synthetic upstream refusal', message: 'synthetic upstream refusal' }, { errcode: 12346, message: '未知错误' }])('rejects unsuccessful uploads without persisting a success cache %#', async value => {
  h.fetch.mockResolvedValueOnce(response({ access_token: 'token', expires_in: 7200 })).mockResolvedValueOnce(response({ errcode: value.errcode, errmsg: value.errmsg }))
  await expect(api.uploadContentImage('key', '/virtual/input')).rejects.toMatchObject({ status: 502, message: expect.stringContaining(value.message) })
  expect(h.write).not.toHaveBeenCalled()
})
it('rejects invalid drafts before token lookup and keeps cache write failures observable', async () => {
  await expect(api.addDraft({ ...draft, title: '' })).rejects.toMatchObject({ status: 400 })
  expect(h.fetch).not.toHaveBeenCalled()
  const failure = Error('synthetic cache write failed')
  h.write.mockRejectedValueOnce(failure)
  h.fetch.mockResolvedValueOnce(response({ access_token: 'token', expires_in: 7200 })).mockResolvedValueOnce(response({ url: 'https://mmbiz.qpic.cn/new' }))
  await expect(api.uploadContentImage('key', '/virtual/input')).rejects.toBe(failure)
})
